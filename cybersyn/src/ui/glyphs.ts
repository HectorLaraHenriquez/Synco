const REEMPLAZOS: Record<string, string> = { '–': '-', '—': '-', '“': '"', '”': '"', '‘': "'", '’': "'", '…': '...', 'Ü': 'U', '\t': ' ' };

/** Reemplaza caracteres sin glifo para que nunca se dibuje un hueco inesperado. */
export function sanitize(text: string): string {
  let out = '';
  for (const ch of text) {
    if (ch === '\n' || GLYPHS[ch]) out += ch;
    else out += REEMPLAZOS[ch] ?? '?';
  }
  return out;
}

/** Corta el texto en líneas de a lo más `cols` caracteres, por palabras. */
export function wrap(text: string, cols: number): string[] {
  const out: string[] = [];
  for (const par of text.split('\n')) {
    let line = '';
    for (const word of par.split(' ')) {
      if (line.length > 0 && line.length + 1 + word.length > cols) {
        out.push(line);
        line = word;
      } else line = line.length > 0 ? `${line} ${word}` : word;
      while (line.length > cols) {
        out.push(line.slice(0, cols));
        line = line.slice(cols);
      }
    }
    out.push(line);
  }
  return out;
}
